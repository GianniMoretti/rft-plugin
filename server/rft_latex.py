#!/usr/bin/env python3
"""The LaTeX of snippets and documents (docs/design/manuscript.md): the files the plugin generates
in vault/documents/, a document compiled to PDF, and a snippet compiled alone. Standard library only.

- **rft.sty**: the macros a snippet takes the tree's numbers, figures and tables with, so none is
  typed by hand: \\rftnum{E05}{acc.1k} (a number of results/E05.json, the notebook's RESULTS as it
  rounds them), \\rftfig[opts]{E08}{loss} (figures/E08_loss.pdf), \\rfttable{E08}{by_seed}
  (tables/E08_by_seed.tex, a booktabs tabular); and the theorem environments a snippet's kind opens, unless the document defines its own. A name that is
  not there prints ?? in bold and is a LaTeX warning, as an undefined reference is.
- **rft-numbers.tex**: every saved RESULTS, as the macros \\rftnum reads.
- **refs.bib**: the reference notes' BibTeX: each ```bibtex block of a note as written (a literature
  note holds one per paper, cited by its own key), and a single-paper note also under its id
  (\\cite{R07}); a reference with no block gets a @misc from its title and its first link.
- **compile**: `latexmk -pdf` in documents/<name>/, its output in documents/.build/<name>/, with
  documents/ and the vault on TEXINPUTS (so `rft.sty`, `figures/…` and `tables/…` are found) and
  shell escape off; stopped after TIMEOUT_S. A document holds copies of its snippets, so it needs
  nothing else. The answer: the PDF, the errors (file and line) and rft's warnings.
- **a snippet alone**: snippets/<id>.tex in a minimal article (the preamble documents start with),
  compiled in documents/.build/_snippets/, so a building block can be read on its own.

    python3 rft_latex.py generate --vault V
    python3 rft_latex.py compile --vault V --doc paper
    python3 rft_latex.py compile --vault V --snippet S04
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rft_results import field, number_text, split_note, tex_text, write_atomic  # noqa: E402

DOCUMENTS = "documents"
TIMEOUT_S = 120
DOC_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")

STY = r"""% rft.sty, generated by the rft plugin each time a document compiles: do not edit it.
\NeedsTeXFormat{LaTeX2e}
\ProvidesPackage{rft}[2026/11/17 rft: the tree's numbers, figures and tables in a manuscript]
\RequirePackage{graphicx}
\RequirePackage{booktabs}
\RequirePackage{amsthm}
\InputIfFileExists{rft-numbers.tex}{}{}
% \rftnum{E05}{acc.1k}: a number a notebook's run saved (results/E05.json)
\newcommand{\rftnum}[2]{\ifcsname rft@num@#1@#2\endcsname\csname rft@num@#1@#2\endcsname\else
  \textbf{??}\PackageWarning{rft}{No number #2 of #1 (results/#1.json)}\fi}
% \rftfig[width=.8\linewidth]{E08}{loss}: figures/E08_loss.pdf
\newcommand{\rftfig}[3][]{\IfFileExists{figures/#2\string_#3.pdf}%
  {\includegraphics[#1]{figures/#2\string_#3.pdf}}%
  {\fbox{\textbf{??} \detokenize{#2: #3}}\PackageWarning{rft}{No figure #3 of #2 (figures/#2\string_#3.pdf)}}}
% \rfttable{E08}{by_seed}: tables/E08_by_seed.tex, a booktabs tabular
\newcommand{\rfttable}[2]{\IfFileExists{tables/#1\string_#2.tex}%
  {\input{tables/#1\string_#2.tex}}%
  {\fbox{\textbf{??} \detokenize{#1: #2}}\PackageWarning{rft}{No table #2 of #1 (tables/#1\string_#2.tex)}}}
% the environments of the snippets' kinds, unless the document has its own
\@ifundefined{theorem}{\theoremstyle{plain}\newtheorem{theorem}{Theorem}}{}
\@ifundefined{lemma}{\theoremstyle{plain}\newtheorem{lemma}[theorem]{Lemma}}{}
\@ifundefined{proposition}{\theoremstyle{plain}\newtheorem{proposition}[theorem]{Proposition}}{}
\@ifundefined{corollary}{\theoremstyle{plain}\newtheorem{corollary}[theorem]{Corollary}}{}
\@ifundefined{definition}{\theoremstyle{definition}\newtheorem{definition}{Definition}}{}
\endinput
"""


def documents_dir(vault: Path) -> Path:
    """Where the documents are, and what the plugin generates for them."""
    return Path(vault) / DOCUMENTS


def leaves(x, key: str = "", out: dict | None = None) -> dict:
    """RESULTS by path (`acc.1k`, `sizes[0]`), as hooks/lib/manuscript.ts flatten has them."""
    out = {} if out is None else out
    if isinstance(x, list):
        for i, v in enumerate(x):
            leaves(v, f"{key}[{i}]", out)
    elif isinstance(x, dict):
        for k, v in x.items():
            leaves(v, f"{key}.{k}" if key else str(k), out)
    elif key:
        out[key] = x
    return out


def numbers_tex(vault: Path) -> str:
    """Every saved RESULTS as the macros \\rftnum reads."""
    lines = ["% rft-numbers.tex, generated by the rft plugin from results/*.json: do not edit it."]
    for f in sorted((Path(vault) / "results").glob("*.json")):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for k, v in leaves(d.get("results")).items():
            if v is None or isinstance(v, bool) or "}" in k or "{" in k:
                continue
            lines.append(f"\\@namedef{{rft@num@{f.stem}@{k}}}{{{tex_text(number_text(v))}}}")
    return "\n".join(lines) + "\n"


def section(text: str, title: str) -> str:
    """A note's `## <title>` section, outside code fences, trimmed."""
    _, body = split_note(text)
    out, inside, fenced = [], False, False
    for line in body.split("\n"):
        if re.match(r"^\s*(```|~~~)", line) and inside:
            fenced = not fenced
        if not fenced and line.startswith("## "):
            if inside:
                break
            inside = line[3:].strip() == title
            continue
        if inside:
            out.append(line)
    return "\n".join(out).strip()


LINK_RE = re.compile(r"(https?://\S+|\b10\.\d{4,9}/\S+|\barXiv:\s*\d{4}\.\d{4,5}(?:v\d+)?)", re.I)
BIB_BLOCK = re.compile(r"```bibtex\n([\s\S]*?)```")
BIB_KEY = re.compile(r"(@\w+\s*\{\s*)([^,\s]+)(\s*,)")


def refs_bib(vault: Path) -> str:
    """The reference notes' BibTeX, as the module's docstring says."""
    out = ["% refs.bib, generated by the rft plugin from the reference notes: do not edit it."]
    seen: set[str] = set()
    for f in sorted((Path(vault) / "references").glob("*.md")):
        text = f.read_text(encoding="utf-8", errors="replace")
        nid = field(text, "id") or f.name.split(" ")[0]
        title = f.name[:-3][len(nid):].strip()
        literature = "literature" in field(text, "tags")
        blocks = [b.strip() for b in BIB_BLOCK.findall(text) if BIB_KEY.search(b)]
        for b in blocks:
            key = BIB_KEY.search(b).group(2)
            if key not in seen:
                seen.add(key)
                out.append(b)
        if nid in seen:
            continue
        seen.add(nid)
        if blocks and not literature:
            out.append(BIB_KEY.sub(lambda m: m.group(1) + nid + m.group(3), blocks[0], count=1))
        elif not literature:
            found = LINK_RE.search(section(text, "Source"))
            link = found.group(1).rstrip(".,;)") if found else ""
            note = f",\n  howpublished = {{\\url{{{link}}}}}" if link.startswith("http") else f",\n  note = {{{tex_text(link)}}}" if link else ""
            out.append(f"@misc{{{nid},\n  title = {{{{{tex_text(title)}}}}}{note}\n}}")
    return "\n\n".join(out) + "\n"


def generate(vault: Path) -> list[str]:
    """Writes rft.sty, rft-numbers.tex and refs.bib in the manuscript's folder; the files written."""
    ms = documents_dir(vault)
    ms.mkdir(parents=True, exist_ok=True)
    files = {"rft.sty": STY, "rft-numbers.tex": numbers_tex(vault), "refs.bib": refs_bib(vault)}
    for name, text in files.items():
        path = ms / name
        if not path.exists() or path.read_text(encoding="utf-8", errors="replace") != text:
            write_atomic(path, text)
    return sorted(files)


ERROR_RE = re.compile(r"^(.*?\.(?:tex|sty|cls|bbl)):(\d+): (.*)$")
RFT_WARNING_RE = re.compile(r"Package rft Warning: (.*?)(?: on input line (\d+))?\.$")
CITE_RE = re.compile(r"LaTeX Warning: (Citation|Reference) [`'](.+?)' .*?undefined on input line (\d+)")


def where(file: str, ms: Path, doc: str) -> dict:
    """A file the log names, as the page shows it: a snippet's id, or the document's main.tex."""
    m = re.search(r"(?:^|/)snippets/(S\d+)\.tex$", file)
    if m:
        return {"file": f"snippets/{m.group(1)}.tex", "snippet": m.group(1)}
    if file.endswith("main.tex"):
        return {"file": f"{DOCUMENTS}/{doc}/main.tex"}
    return {"file": file.replace(str(ms.parent) + "/", "")}


def read_log(log: str, ms: Path, doc: str) -> tuple[list[dict], list[str]]:
    """The errors of a log (file, line, message, the lines after it) and rft's and the citations' warnings."""
    errors, warnings = [], []
    lines = log.splitlines()
    for i, line in enumerate(lines):
        m = ERROR_RE.match(line)
        if m and m.group(3).strip().startswith("==> Fatal error occurred"):
            continue  # TeX's last word after an error, not one of its own
        if m:
            context = " ".join(x.strip() for x in lines[i + 1:i + 3] if x.strip() and not x.startswith("!"))
            errors.append({**where(m.group(1), ms, doc), "line": int(m.group(2)), "message": m.group(3).strip(), "context": context[:200]})
        elif line.startswith("! ") and not errors:
            errors.append({"file": f"{DOCUMENTS}/{doc}/main.tex", "line": None, "message": line[2:].strip(), "context": ""})
        w = RFT_WARNING_RE.search(line)
        if w:
            warnings.append(w.group(1).replace("(rft)", "").strip())
        c = CITE_RE.search(line)
        if c:
            warnings.append(f"{c.group(1)} {c.group(2)} undefined")
    return errors, list(dict.fromkeys(warnings))


def stop(proc: subprocess.Popen) -> None:
    try:
        os.killpg(proc.pid, signal.SIGTERM)
        proc.wait(5)
    except (OSError, subprocess.TimeoutExpired):
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except OSError:
            pass


def _latexmk(vault: Path, src: Path, out: Path, doc: str, timeout: float) -> dict:
    """latexmk on `src` (its folder the working one), its output in `out`, after rft's files are generated."""
    if not shutil.which("latexmk"):
        return {"ok": False, "error": "latexmk is not on PATH: install a TeX distribution (TeX Live, with latexmk) to compile"}
    ms = documents_dir(vault)
    generate(vault)
    out.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "TEXINPUTS": f"{ms}{os.pathsep}{vault}{os.pathsep}", "BIBINPUTS": f"{ms}{os.pathsep}",
           "shell_escape": "f", "max_print_line": "1000"}
    cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "-file-line-error", f"-outdir={out}", src.name]
    t = time.monotonic()
    proc = subprocess.Popen(cmd, cwd=src.parent, env=env, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL, start_new_session=True)
    try:
        proc.wait(timeout)
    except subprocess.TimeoutExpired:
        stop(proc)
        return {"ok": False, "seconds": round(time.monotonic() - t, 1), "error": f"the compile took more than {timeout:g} s: stopped"}
    seconds = round(time.monotonic() - t, 1)
    log_path = out / f"{src.stem}.log"
    log = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else ""
    errors, warnings = read_log(log, ms, doc)
    pdf = out / f"{src.stem}.pdf"
    ok = proc.returncode == 0 and pdf.exists()
    answer = {"ok": ok, "seconds": seconds, "errors": errors, "warnings": warnings}
    if pdf.exists():
        answer["pdf"] = str(pdf)
    if not ok and not errors:
        answer["error"] = f"latexmk exited with {proc.returncode}; see {log_path}"
    return answer


def compile_doc(vault: Path, doc: str, timeout: float = TIMEOUT_S) -> dict:
    """Compiles documents/<doc>/main.tex to documents/.build/<doc>/main.pdf."""
    vault = Path(vault).resolve()
    src = documents_dir(vault) / doc / "main.tex"
    if not DOC_RE.match(doc) or not src.is_file():
        return {"ok": False, "error": f"no document {doc}"}
    return _latexmk(vault, src, documents_dir(vault) / ".build" / doc, doc, timeout)


SNIPPET_ID = re.compile(r"^S\d+$")
PREVIEW = r"""\documentclass[11pt]{article}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{amsmath,amssymb,amsthm}
\usepackage{graphicx,booktabs}
\usepackage[numbers]{natbib}
\usepackage{rft}
\usepackage{hyperref}
\pagestyle{empty}
\begin{document}
\input{snippets/%(id)s.tex}
%(bib)s\end{document}
"""


def compile_snippet(vault: Path, sid: str, timeout: float = TIMEOUT_S) -> dict:
    """Compiles one snippet alone, in the minimal article documents start with, to
    documents/.build/_snippets/<id>.pdf: a building block read on its own."""
    vault = Path(vault).resolve()
    snippet = vault / "snippets" / f"{sid}.tex"
    if not SNIPPET_ID.match(sid or "") or not snippet.is_file():
        return {"ok": False, "error": f"no snippet {sid}"}
    out = documents_dir(vault) / ".build" / "_snippets"
    out.mkdir(parents=True, exist_ok=True)
    cites = re.search(r"\\cite\w*\*?(\[[^\]]*\]){0,2}\{", "\n".join(re.sub(r"(^|[^\\])%.*$", r"\1", l) for l in snippet.read_text(encoding="utf-8", errors="replace").split("\n")))
    bib = "\\bibliographystyle{plainnat}\n\\bibliography{refs}\n" if cites else ""
    wrapper = out / f"{sid}.tex"
    wrapper.write_text(PREVIEW % {"id": sid, "bib": bib}, encoding="utf-8")
    return _latexmk(vault, wrapper, out, "_snippets", timeout)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("what", choices=["generate", "compile"])
    p.add_argument("--vault", required=True)
    p.add_argument("--doc")
    p.add_argument("--snippet")
    p.add_argument("--timeout", type=float, default=TIMEOUT_S)
    a = p.parse_args(argv)
    if a.what == "generate":
        print(json.dumps({"written": generate(Path(a.vault))}))
        return 0
    if not a.doc and not a.snippet:
        p.error("compile needs --doc or --snippet")
    r = compile_snippet(Path(a.vault), a.snippet, a.timeout) if a.snippet else compile_doc(Path(a.vault), a.doc, a.timeout)
    print(json.dumps(r))
    return 0 if r["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
